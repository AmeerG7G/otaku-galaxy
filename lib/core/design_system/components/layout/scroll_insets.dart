import 'package:flutter/widgets.dart';

/// ما يغطّي أسفل الجسم، والحشوة التي يتجاوزه بها آخرُ المحتوى.
///
/// [CRITICAL] المسافة السفلية تُقرأ من `MediaQuery.paddingOf(context).bottom`
/// وحدها — لا من رقمٍ مكتوب. فلاتر يُبقي هذه القيمة صادقة في كل سياق:
///
/// - **شاشة مدفوعة** (`Scaffold` بلا شريط سفلي): هي إزاحة النظام — صفر، أو
///   ~٢٤ لمؤشّر الإيماءات، أو ~٤٨ للأزرار الثلاثة. التطبيق في `edgeToEdge`
///   (`bootstrap.dart`)، فالجسم يمتدّ تحتها.
/// - **تبويبٌ تحت الغلاف الرئيسي** (`Scaffold(extendBody: true)`): هي ارتفاع
///   الشريط العائم كاملاً، وفيه إزاحة النظام وأثر تكبير الخط على تسمياته.
/// - **تحت `SafeArea` سفلية، أو فوق شريطٍ في `bottomNavigationBar`**: صفر —
///   استُهلكت، فلا تُضاف مرّتين.
/// - **لوحة المفاتيح مفتوحة**: صفر أيضاً؛ هي التي تغطّي شريط النظام الآن،
///   و`Scaffold` يقلّص الجسم فوقها.
///
/// العطب الذي أُصلح بهذا (Staging، 2026-10): كل مُمرِّر كتب حشوته السفلية
/// رقماً — ١٠٤ تحت الشريط العائم (منسوخةً من مرجعٍ لا إزاحة نظامٍ في إطاره)،
/// و٢٦ في الشاشات المدفوعة. على هاتفٍ بالأزرار الثلاثة كان زرّ «تسجيل
/// الخروج» يقع تحت الشريط إلا ٣ بكسلات. `test/bottom_inset_layout_test.dart`
/// يقيس النتيجة عبر المقاسات والإزاحات وأحجام الخطّ.
extension BottomInsetContext on BuildContext {
  /// ارتفاع ما يغطّي أسفل هذا الجسم الآن (شريط النظام أو الشريط العائم).
  double get bottomOverlap => MediaQuery.paddingOf(this).bottom;

  /// حشوة مُمرِّرٍ رأسيّ: حشوة التصميم [design] كما هي، وفوق حدّها السفلي
  /// ما يغطّي أسفل الجسم.
  ///
  /// المحتوى يبقى ممتدّاً خلف الشريط أثناء التمرير، وآخر عنصرٍ يصل فوقه
  /// كاملاً بمسافة التصميم نفسها على كل جهاز.
  EdgeInsets scrollPadding(EdgeInsets design) =>
      design.copyWith(bottom: design.bottom + bottomOverlap);
}
