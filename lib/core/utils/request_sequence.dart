/// رقمٌ تسلسلي لطلبات شاشةٍ تُعيد الجلب في موضعها.
///
/// [CRITICAL] الردّ الذي يصل بعد أن تجاوزه المستخدم يجب أن يُهمَل، لا أن
/// يُكتب في الحالة. كانت شاشات القسم والمجتمع والبحث تكتب أيّ ردٍّ يصل:
/// يختار المستخدم «ب» بينما ردّ «أ» ما زال في الطريق، فيصل «أ» بعد «ب»
/// ويطمسه — تظهر منتجات قسمٍ والترويسة تقول قسماً آخر، ثم «يتصحّح» الوضع
/// مع ردٍّ لاحق. هذا هو الوميض الذي رآه المستخدم، وليس ذاكرة الصور.
///
/// الاستعمال: `final token = _requests.next();` قبل أي `await`، ثم بعد كل
/// `await`: `if (!mounted || !_requests.isCurrent(token)) return;`.
class RequestSequence {
  int _current = 0;

  /// يبدأ طلباً جديداً ويعيد رقمه — كل ما سبقه يصير متجاوَزاً.
  int next() => ++_current;

  /// هل هذا الرقم هو أحدث طلب؟
  bool isCurrent(int token) => token == _current;
}
