/// وصول سريع للنصوص المترجمة حسب لغة المستخدم الحالية.
extension AppStringsContext on BuildContext {
  /// نصوص الواجهة بلغة الجلسة، أو العربية إن لم تكن هناك جلسة.
  ///
  /// [CRITICAL] غياب `LocaleCubit` من الشجرة لا يرمي استثناءً — بنفس منطق
  /// [GenderedContext.gender]. المكعّب موفَّر في جذر التطبيق
  /// (`app.dart`)، لكن الاستدعاء يقع في **ودجات عرض** قد تُبنى في شجرة
  /// معزولة: حوارٌ بمُنقِّله الخاص، أو شاشةٌ تُبنى وحدها في اختبار. الارتداد
  /// إلى العربية هو سلوك [AppStrings.of] نفسه للغة الافتراضية، فلا يغيّر
  /// شيئاً في الإنتاج.
  ///
  /// وأن الجذر يوفّره فعلاً ليس متروكاً للثقة: يحرسه
  /// `app_provides_locale_cubit` في `localization_corpus_test.dart`.
  ///
  /// [CRITICAL] الاعتماد الموروث عبر [LocaleScope] أولاً، لا `read` وحده.
  /// النصوص تُقرأ في معالِجات الأحداث بقدر ما تُقرأ في `build` — رسالةُ
  /// تحقّقٍ من مُدقِّق حقل، أو نصُّ بوابة تسجيل دخول داخل `onPressed` —
  /// و`watch` خارج `build` يرمي فوراً، فكان الاختيار `read`. لكن `read` لا
  /// يسجّل اعتماداً، وإعادةُ بناء `MaterialApp` **لا** تعيد بناء الشاشات
  /// المركّبة (انظر [LocaleScope])، فبقيت الشاشات المفتوحة بلغتها القديمة
  /// بعد التبديل. الاعتماد الموروث يجمع الاثنين: جائز خارج `build`، ويعيد
  /// رسم من قرأ نصّاً حين تتبدّل اللغة. `LocaleCubit` احتياطٌ للشجرة التي
  /// لا يعلوها [LocaleScope]، والعربية احتياط الاحتياط.
  AppStrings get strings => AppStrings.of(language);
}

/// لغة الواجهة الحالية مع اعتماد موروث — انظر [AppStringsContext.strings].
extension AppLanguageContext on BuildContext {
  AppLanguage get language {
    final scoped = LocaleScope.maybeOf(this);
    if (scoped != null) return scoped;
    try {
      return read<LocaleCubit>().state;
    } on ProviderNotFoundException {
      return AppLanguage.arabic;
    }
  }
}
