  /// يخصّ كل لغة. تركيبُ الجملة من أجزاء مترجَمة حول متغيّر (`'مرحباً ' + name`)
  /// كان سيفرض ترتيب العربية على الكردية ويكسرها.
  ///
  /// المتغيّر الذي لا تُمرَّر له قيمة يبقى ظاهراً كما هو (`{name}`) بدل أن
  /// يُحذف بصمت: نصٌّ مكسور ظاهر يُصلَح، ونصٌّ ناقص بهدوء لا يُلاحَظ.
  String p(String key, Map<String, String> args) {
    var value = call(key);
    for (final entry in args.entries) {
      value = value.replaceAll('{${entry.key}}', entry.value);
    }
    return value;
  }

