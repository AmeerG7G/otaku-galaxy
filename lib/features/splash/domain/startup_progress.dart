import 'package:flutter/foundation.dart';

/// خطوات الإقلاع **المطلوبة** — قائمة محدودة معروفة قبل التشغيل.
///
/// [CRITICAL] «مطلوبة» تعني: لا يجوز عرض الشاشة الأولى قبل تمامها. كل ما
/// عداها يعمل في الخلفية ولا يدخل هذا التعداد ولا يؤخّر الانتقال —
/// إعدادات المتجر مثلاً: إقلاعٌ ينتظر الشبكة هو إقلاعٌ يفشل معها.
///
/// (كانت هنا خطوة `visuals` تدفّئ رسوم الشخصيات المُدارة من القرص؛ أُزيلت مع
/// ميزة «رسوم الشخصيات» في 2026-09-27 — الشخصيات أصولٌ ثابتة في الحزمة.)
enum StartupStep {
  /// تفضيلات محفوظة جاهزة (التعريف، اللغة، المظهر) — يقرّر بها التوجيه وجهته.
  preferences,

  /// استعادة جلسة المصادقة — العمل الوحيد المجهول المدة في الإقلاع.
  session,

  /// لحظة الهوية: مدة العرض الدنيا لشاشة البداية.
  ///
  /// خطوةٌ معلَنة لا تأخيرٌ مخفيّ. مرجع التصميم يحدّد ٢٫٣ ثانية، وإدراجُها
  /// في النموذج هو ما يجعل الشريط صادقاً: لو استُبعدت لبلغ ١٠٠٪ ثم جلس
  /// ساكناً حتى ينتهي انتظارٌ لا يمثّله شيء — وهو العطب نفسه من جهة أخرى.
  brandMoment,
}

/// تقدّم الإقلاع — المصدر الوحيد لكل من شريط التحميل وقرار الانتقال.
///
/// [CRITICAL] العقد: `progress` تبلغ ١ **إذا وفقط إذا** تمّت كل الخطوات،
/// و[isComplete] هي شرط الانتقال الوحيد. قبل هذا كان الشريط حركةً زمنية
/// (`AnimationController` مدته ٢٫٣ث) والانتقال مؤقّتاً مستقلاً
/// (`Future.delayed`) — رقمان لا يعرف أحدهما الآخر:
///
///   • المؤقّت يبدأ عند `initState`، والحركة لا تبدأ إلا مع أول إطار. أي
///     تأخّرٍ في أول إطار (حقن الاعتماديات، فكّ ترميز الصور) يجعل الحركة
///     تنتهي بعد المؤقّت، فينتقل التطبيق **والشريط لم يبلغ نهايته** — وهو
///     ما يراه المستخدم.
///   • وإن طالت استعادة الجلسة بلغ الشريط ١٠٠٪ وجلس ينتظر عملاً لم ينتهِ.
///
/// النموذج هنا يزيل الاحتمالين: لا رقم ثانٍ يُقارن به.
class StartupProgress extends ChangeNotifier {
  final Set<StartupStep> _completed = <StartupStep>{};
  Object? _failure;

  /// الخطوات المنجزة — للقراءة فقط.
  Set<StartupStep> get completed => Set.unmodifiable(_completed);

  /// نسبة الإنجاز من ٠ إلى ١.
  double get progress => _completed.length / StartupStep.values.length;

  /// هل تمّت كل الخطوات المطلوبة؟ شرط الانتقال الوحيد.
  bool get isComplete =>
      _failure == null && _completed.length == StartupStep.values.length;

  /// خطأ أوقف الإقلاع — `null` ما دام سليماً.
  Object? get failure => _failure;

  bool get hasFailed => _failure != null;

  /// يسجّل تمام خطوة. التكرار لا يفعل شيئاً — إعادة النداء ليست تقدّماً.
  void complete(StartupStep step) {
    if (_failure != null) return;
    if (_completed.add(step)) notifyListeners();
  }

  /// يوقف الإقلاع بخطأ.
  ///
  /// [CRITICAL] لا يُكمل الخطوات ولا يرفع النسبة: الشاشة تعرض إعادة
  /// المحاولة، ولا تنتقل إلى تطبيقٍ نصفِ مُهيَّأ. `isComplete` تبقى false
  /// مهما بلغ عدد ما تمّ قبل العطب.
  void fail(Object error) {
    if (_failure != null) return;
    _failure = error;
    notifyListeners();
  }

  /// يعيد الحالة إلى الصفر — لزرّ «إعادة المحاولة».
  void reset() {
    _completed.clear();
    _failure = null;
    notifyListeners();
  }
}
