/**
 * التمثيل المعتمد لرقم الهاتف — تنفيذ واحد لا غير.
 *
 * [CRITICAL] كان الرقم يُخزَّن ويُمرَّر بصيغته المحلية `07XXXXXXXXX`، وهي
 * الصيغة نفسها التي تُسلَّم لمزوّد الرسائل. مزوّدو الرسائل يطلبون E.164
 * (`+9647XXXXXXXXX`)؛ الصيغة المحلية تُرفض أو — أسوأ — تُقبل ولا تُسلَّم،
 * فيبدو التسجيل ناجحاً بينما لا تصل رسالة واحدة.
 *
 * الصيغة المعتمدة داخلياً هي E.164: `+9647XXXXXXXXX`. كل مدخل يمرّ من هنا
 * قبل أن يُخزَّن أو يُقارَن أو يُرسَل، فلا يوجد في القاعدة تمثيلان لرقم واحد.
 */

/** رمز العراق الدولي. */
const IRAQ_CALLING_CODE = '964';

/** البادئة المعتمدة للأرقام المخزَّنة. */
export const IRAQ_PHONE_PREFIX = `+${IRAQ_CALLING_CODE}`;

/**
 * الرقم الوطني بعد نزع الرمز الدولي: `7` ثم تسعة أرقام.
 *
 * الخانة الثانية محصورة في `[5-9]` لأن نطاقات المحمول المخصَّصة في العراق هي
 * ‎075 و076 و077 و078 و079 — وهي تغطي المشغّلين جميعاً (كورك، آسياسيل، زين،
 * ومن يليهم) لا مشغّلاً بعينه. النطاقات ‎070–074 ليست نطاقات محمول مخصَّصة،
 * فقبولها يعني تمرير رقم لن تصله رسالة أبداً.
 *
 * تُوسَّع هذه القاعدة بتعديل هذا الثابت وحده متى خُصِّص نطاق جديد.
 */
const NATIONAL_MOBILE = /^7[5-9]\d{8}$/;

/**
 * تحويل أي صيغة عراقية معقولة إلى الصيغة المعتمدة، أو `null` إن كانت غير صالحة.
 *
 * المقبول: `07XXXXXXXXX` · `7XXXXXXXXX` · `9647XXXXXXXXX` ·
 * `+9647XXXXXXXXX` · `009647XXXXXXXXX`.
 *
 * المرفوض: الحروف، الطول الخاطئ، الرمز الدولي المكرَّر (`+964964…`)، البادئات
 * غير المخصَّصة، والفواصل الداخلية.
 *
 * الفواصل المألوفة (فراغ، شَرطة، قوسان، نقطة) تُنزَع لا تُرفض. حقلُ الهاتف
 * في التطبيق يقترح على المستخدم `0770 123 4567` بفراغاته، فرفضُها كان
 * سيعاقبه على اتّباع ما عُرض عليه.
 *
 * [CRITICAL] النزع لا يفتح باب تجاوز: `0770 123 4567` و`07701234567`
 * ينتهيان إلى **النصّ نفسه**، فلا يصيران هويّتين لرقم واحد. الخطر يقع حين
 * يُخزَّن الشكل الخام كما ورد — عندها يصير الفراغ رقماً جديداً بحصّة رموز
 * جديدة ويلتفّ على قيد التفرّد. التوحيد هو ما يمنع ذلك، لا الرفض.
 *
 * أما محارف التحكّم (سطر جديد، جدولة) فتُرفض: ليست فواصل هاتف، ووجودها
 * علامةُ لصقٍ فاسد أو محاولة حقن لا خطأ كتابة.
 */
export function normalizeIraqiPhone(raw: unknown): string | null {
  if (typeof raw !== 'string') return null;

  // الفواصل المألوفة وحدها — لا محارف تحكّم ولا أي رمز آخر.
  const trimmed = raw.trim().replace(/[ ()\-.]/g, '');
  // `+` اختيارية في المقدّمة، ثم أرقام لا شيء غيرها.
  if (!/^\+?\d+$/.test(trimmed)) return null;

  const digits = trimmed.startsWith('+') ? trimmed.slice(1) : trimmed;

  // الترتيب مقصود: `00964` قبل `964` قبل `0`. الرقم الوطني يبدأ بـ`7` دائماً،
  // فلا يلتبس نزعُ الرمز الدولي بنزع صفر البداية.
  let national: string;
  if (digits.startsWith(`00${IRAQ_CALLING_CODE}`)) {
    national = digits.slice(2 + IRAQ_CALLING_CODE.length);
  } else if (digits.startsWith(IRAQ_CALLING_CODE)) {
    national = digits.slice(IRAQ_CALLING_CODE.length);
  } else if (digits.startsWith('0')) {
    national = digits.slice(1);
  } else {
    national = digits;
  }

  if (!NATIONAL_MOBILE.test(national)) return null;
  return `${IRAQ_PHONE_PREFIX}${national}`;
}

/** هل النصّ رقمٌ عراقي صالح؟ */
export function isValidIraqiPhone(raw: unknown): boolean {
  return normalizeIraqiPhone(raw) !== null;
}

/**
 * جزء الرقم الذي يُبحث به في لوحة التحكم.
 *
 * المخزَّن صار `+9647701234567`، والمسؤول يكتب ما اعتاده: `07701234567` أو
 * `0770 123` أو الرقم الدولي. نزعُ ما ليس رقماً ثم نزعُ أصفار البداية يجعل
 * الأشكال الثلاثة تنتهي إلى نفس المقطع (`7701234567`) وهو موجود داخل
 * المخزَّن، فيبقى البحث القديم صالحاً بعد التحويل.
 */
export function phoneSearchFragment(search: string): string | null {
  const digits = search.replace(/\D/g, '').replace(/^0+/, '');
  return digits.length >= 3 ? digits : null;
}
