/**
 * تقريب مبالغ الخصم بالدينار العراقي — القاعدة الواحدة لكل خصمٍ محسوب.
 *
 * ═══ القاعدة (قرار المالك 2026-09-27) ═══
 *   خصمٌ محسوب موجب ← أقرب مضاعفٍ لـ٢٥٠، والنصف يُقرَّب صعوداً،
 *                      وأدنى خصمٍ ناتج ٢٥٠:
 *                      max(250, round(calculated / 250) × 250)
 *   لا خصم (صفر، سالب، غير عدد) ← صفر. الحدّ الأدنى لخصمٍ **موجود**، لا
 *                      خصمٌ يُخلق من لا شيء.
 *
 *   89 → 250 · 124 → 250 · 125 → 250 · 251 → 250 · 374 → 250 · 375 → 500
 *   624 → 500 · 625 → 750 · 749 → 750 · 876 → 1000
 *
 * [CRITICAL] تُطبَّق على **القيمة المحسوبة الخام** (النسبة من مجموع المنتجات
 * بعد السقف) لا على قيمةٍ قُرّبت قبلها إلى دينار: التقريب المزدوج يغيّر
 * النتيجة عند الحدود (٣٧٤٫٧٥ ← ٣٧٥ ← ٥٠٠، والصحيح ٢٥٠).
 *
 * [CRITICAL] من يحسب خصماً يستدعي [roundDiscountIqd] ولا يعيد اشتقاقها. أسعار
 * المنتجات والإجمالي ورسوم التوصيل وترويجها (مبلغٌ يضبطه المسؤول لا خصمٌ
 * محسوب) خارج هذه القاعدة.
 *
 * ═══ الدقّة ═══
 * القسمة على ٢٥٠ لا تقع على حدّ النصف خطأً: ٢٥٠ ليست قوةً لـ٢، فأكبر عددٍ عشري
 * دون الحدّ يُقسم إلى ما دون `k + 0.5` لا عليه، و`Math.round` يقرّب النصف
 * صعوداً. `discount-rounding.test.ts` يثبت ذلك عند كل حدّ ± وحدة دقّة، ولكل
 * مبلغ صحيح، وللنسب من كل مجموعٍ صحيح مقابل مرجعٍ بحسابٍ صحيح تام (BigInt).
 */

/** أصغر وحدة يُعبَّر بها عن الخصم — أصغر ورقة نقدية عراقية متداولة. */
export const DISCOUNT_STEP_IQD = 250;

/** مبلغ الخصم المحسوب مقرَّباً بالقاعدة أعلاه. */
export function roundDiscountIqd(calculated: number): number {
  if (!Number.isFinite(calculated) || calculated <= 0) return 0;
  return Math.max(
    DISCOUNT_STEP_IQD,
    Math.round(calculated / DISCOUNT_STEP_IQD) * DISCOUNT_STEP_IQD,
  );
}

/**
 * أكبر خصمٍ مقرَّب يتّسع له [amount]: أكبر مضاعفٍ لـ٢٥٠ لا يتجاوزه.
 *
 * سقفٌ لا تقريب: خصمٌ لا يتجاوز ما يُطبَّق عليه (مجموع المنتجات، سقف المزيّة)
 * ويبقى مضاعفاً لـ٢٥٠ معاً. تحت ٢٥٠ لا يتّسع أي خصم ⇒ صفر.
 */
export function discountCeilingIqd(amount: number): number {
  if (!Number.isFinite(amount) || amount <= 0) return 0;
  return Math.floor(amount / DISCOUNT_STEP_IQD) * DISCOUNT_STEP_IQD;
}
