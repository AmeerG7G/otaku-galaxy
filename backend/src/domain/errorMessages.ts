/** القوالب — الأجزاء المتغيّرة تُلتقط وتُعاد في موضعها. */
const PATTERNS: ReadonlyArray<readonly [RegExp, (m: RegExpMatchArray) => string]> = [
  [/^«(.+)» لم يعد متاحاً — أزله من العربة$/, (m) => `«${m[1]}» ئیتر بەردەست نییە — لە سەبەتە لایبە`],
  [/^تغيّر سعر «(.+)» — راجع سلتك قبل الإرسال$/, (m) => `نرخی «${m[1]}» گۆڕا — پێش ناردن سەبەتەکەت پشکنین بکە`],
  [/^مخزون «(.+)» غير كافٍ \(المتاح: (\d+)\)$/, (m) => `کۆگای «${m[1]}» بەش ناکات (بەردەست: ${m[2]})`],
  [/^الكمية المطلوبة تتجاوز المخزون المتاح \((\d+)\)$/, (m) => `بڕی داواکراو لە کۆگای بەردەست زیاترە (${m[1]})`],
  [/^تحتاج (\d+) نقطة لفتح هذه المزيّة$/, (m) => `پێویستت بە ${m[1]} خاڵە بۆ کردنەوەی ئەم خەڵاتە`],
  [/^الحد الأقصى (\d+) صور للتقييم الواحد$/, (m) => `زۆرترین ${m[1]} وێنە بۆ هەر هەڵسەنگاندنێک`],
  [/^حجم الصورة أكبر من الحدّ المسموح \((\d+) ميغابايت\)$/, (m) => `قەبارەی وێنە لە سنووری ڕێگەپێدراو گەورەترە (${m[1]} مێگابایت)`],
  [/^انتظر (\d+) ثانية قبل طلب رمز جديد$/, (m) => `${m[1]} چرکە چاوەڕێ بکە پێش داواکردنی کۆدێکی نوێ`],
];

/**
 * الرسالة بلغة الطالب. العربية تعود كما هي؛ الكردية تُطابَق حرفياً ثم بالقوالب،
 * وما لم يُطابَق يعود عربياً — سقوطٌ معلَن.
 */
export function localizeErrorMessage(message: string, locale: AppLocale): string {
  if (locale !== 'ckb') return message;
  const exact = EXACT[message];
  if (exact !== undefined) return exact;
  for (const [pattern, render] of PATTERNS) {
    const match = message.match(pattern);
    if (match) return render(match);
  }
  return message;
}

