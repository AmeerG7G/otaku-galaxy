-- 040_user_gender.sql
-- جنس صاحب الحساب — لتوافق النصّ العربي معه نحوياً.
--
-- العربية تُصرّف الخطاب: «أضف» و«أضيفي»، «بطل المجرة» و«بطلة المجرة». تطبيقٌ
-- يخاطب الجميع بالمذكّر يخطئ في حقّ نصف زبائنه في كل جملة.
--
-- [CRITICAL] الحقل يقبل NULL، والحسابات القائمة تبقى NULL. لا استنتاج من
-- الاسم ولا افتراض «مذكّر حتى يثبت العكس»: نسبةُ الخطأ في تخمين كهذا عالية،
-- وأثرُه أن يُخاطَب الزبون بصيغةٍ ليست له بينما لم يُسأل أصلاً. المجهول
-- يُعامَل بصيغة محايدة في طبقة العرض (`AppGender.unknown`)، والتسجيل الجديد
-- يطلب الاختيار صراحةً.
ALTER TABLE users
  ADD COLUMN gender TEXT
    CHECK (gender IS NULL OR gender IN ('male', 'female'));
