-- 049_drop_otp_slot.sql
-- إسقاط فتحة شاشةٍ لم تعد موجودة، وتصحيح وصف فتحةٍ تعدّها.
--
-- شاشة رمز التحقق أُزيلت من التطبيق مع الانتقال إلى الحسابات التي يعتمدها
-- المسؤول (الهجرة ٠٤٨؛ الشاشة محفوظة للتاريخ في `legacy/otp/`). فتحتها
-- `otp_character` بقيت في اللوحة كموضعٍ حيّ: يرفع إليها المسؤول صورةً لا
-- تظهر في أي شاشة — وهو أسوأ من غيابها، لأنها تَعِد بشيء لا يقع. نفس قرار
-- الهجرة ٠٣١ ونفس أثره: الصور المرتبطة تسقط معها (ON DELETE CASCADE)،
-- وسجلّات `media_files` والملفات على القرص تبقى — حذفها قرار تنظيف منفصل.
DELETE FROM visual_slots WHERE slot_key = 'otp_character';

-- لوحة المصادقة (`auth_cta_character`) كانت تخدم أربع شاشات؛ بعد إزالة رمز
-- التحقق صارت ثلاثاً: الدخول، إنشاء الحساب، استعادة كلمة المرور. يُصحَّح
-- النصّ المزروع وحده — وصفٌ عدّله المسؤول بيده لا يُمسّ.
UPDATE visual_slots
   SET location = 'اللوحة السفلية في شاشات المصادقة الثلاث'
 WHERE slot_key = 'auth_cta_character'
   AND location = 'اللوحة السفلية في شاشات المصادقة الأربع';
