-- 062_retire_empty_categories_slot.sql
-- شخصية قائمة الأقسام الفارغة لم تعد مطلوبة — تبويب الأقسام يستخدم أصلاً مضمَّناً بلا فتحة.
--
-- الفتحة `empty_categories_character` كانت تستهلكها شاشة تبويب الأقسام حين
-- تكون فارغة، لكن التصميم الحالي يعرض الرسم المضمَّن مباشرة دون ربط باللوحة.
-- بقاؤها في الفهرس يعدل المسؤول بصورةٍ لا تظهر عند أحد.
--
-- لا صور مرتبطة (الفتحة لم تُضبط بصورة مخصصة)، لذا الحذف مباشر.

DELETE FROM visual_slots
 WHERE slot_key = 'empty_categories_character';