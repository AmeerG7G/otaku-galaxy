-- 059_remove_empty_collection_slot.sql
-- شخصية المجموعة الفارغة لم تعد مفيدة — الشاشة تستخدم أصلاً مضمَّناً بلا فتحة.
--
-- الفتحة `empty_collection_character` كانت تستهلكها شاشة تفاصيل المجموعة حين
-- تكون فارغة، لكن التصميم الحالي يعرض الرسم المضمَّن مباشرة دون ربط باللوحة.
-- بقاؤها في الفهرس يعدل المسؤول بصورةٍ لا تظهر عند أحد.
--
-- لا صور مرتبطة (الفتحة لم تُضبط بصورة مخصصة)، لذا الحذف مباشر.

DELETE FROM visual_slots
 WHERE slot_key = 'empty_collection_character';