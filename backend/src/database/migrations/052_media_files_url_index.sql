--
-- فهرسٌ على `media_files.url`.
--
-- كان البحث بالمرجع (`mediaRepo.findByUrl`) مسحاً كاملاً للجدول: الفهارس
-- القائمة على `storage_key` (فريد) و`(uploaded_by, created_at)`
-- و`(purpose, created_at)` لا تخدمه. صار هذا البحث إلزامياً في كل إرسالٍ
-- أو إعادة إرسالٍ لتقييم (حتى خمس صور) وفي كل تغييرٍ للصورة الشخصية بعد
-- فحص الملكية (تدقيق 2026-09-14)، فكلفتُه تنمو مع كل رفعٍ في المتجر.
--
-- غير فريد عمداً: المرجع فريدٌ بالبناء (`publicPath/storage_key`) لكن
-- الفهرس لا يفرض ما لم يفرضه المخطّط سلفاً — تسويةٌ لاحقة قد تُصلح مرجعاً
-- بالضبط كما تُصلح آخر.

CREATE INDEX IF NOT EXISTS idx_media_files_url ON media_files (url);
