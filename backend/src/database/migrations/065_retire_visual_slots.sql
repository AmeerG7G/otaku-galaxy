-- 065_retire_visual_slots.sql
-- إزالة ميزة «رسوم الشخصيات» من لوحة التحكم — الشخصيات صارت أصولاً ثابتة.
--
-- ═══ القرار (2026-09-27) ═══
-- رسوم الشخصيات لم تعد تُدار من اللوحة. الصور التي كانت مختارةً لكل موضع
-- نُسخت إلى التطبيق أصولاً ثابتة (`assets/art/characters/`) بايتاً ببايت،
-- ويحدّدها الكود (`CharacterArt` في `lib/features/visuals/domain/visual_slot.dart`)
-- لا بيانات القاعدة. لا مستهلك لهذا الجدول بعد اليوم: مسارات
-- `/admin/visual-slots*` و`/catalog/visuals` حُذفت، ومرجع الوسائط
-- (`mediaRepo.MEDIA_REFERENCE_COLUMNS` و`findUnreferenced`) لم يعد يقرؤه.
--
-- الأمان:
--   * لا جدول آخر يشير إلى `visual_slots` (جدول الصور القديم أُسقط في 054).
--   * ملفات الصور المرفوعة (`media_files.purpose = 'slot'` و`uploads/slot/`)
--     **لا تُحذف**: الحذف الآلي للوسائط غير موجود أصلاً (`findUnreferenced`
--     قراءةٌ للتشخيص فقط)، وصفوفها التاريخية تبقى كما هي. `purpose = 'slot'`
--     يبقى مسموحاً في قيد `media_files` لهذه الصفوف، ولا يقبله الرفع بعد اليوم.
--   * الفهرس والمشغّل المعرَّفان على الجدول يسقطان معه.

DROP TABLE IF EXISTS visual_slots;
