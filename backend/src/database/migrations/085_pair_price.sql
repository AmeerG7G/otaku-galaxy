-- 085_pair_price.sql
-- «قطعة بـ٤٠٠٠، قطعتان بـ٧٠٠٠»: سعر قطعتين لكل منتج (STEP 69، 2026-10-24).
--
-- قرار المالك: حقلٌ اختياري يضبطه المسؤول لكل منتج. يسري على قطعتين من
-- **المنتج نفسه** وإن اختلف الخيار، ويتكرّر (٣ = ١١٠٠٠، ٤ = ١٤٠٠٠). منتجٌ بلا
-- هذا الحقل (NULL) يبقى على سعره كما هو. خصما الميلاد والمزيّة يُحسبان على
-- مجموع المنتجات الناتج كما اليوم. الحساب في `domain/orderPricing.ts`
-- (`pairPricedLineTotals`) وحده — لا مبلغ من العميل.
--
-- القيد يجعل كل قيمةٍ محفوظة عرضاً حقيقياً:
--   • لا سعر قطعتين بلا سعر قطعة — منتجٌ «قريباً» (084) لا عرض له.
--   • `pair_price >= price`: قطعتان لا تكونان أرخص من قطعة واحدة، فلا يصير
--     سطرٌ سالباً (التوفير على القطعة الثانية لا يتجاوز سعرها).
--   • `pair_price < 2 * price`: سعرٌ لا يوفّر شيئاً (أو يزيد) ليس عرضاً، ويُرفض
--     بدل أن يُعرض على الزبون شارةُ عرضٍ بلا توفير.
-- وتعديل سعر القطعة لاحقاً يمرّ من القيد نفسه: سعرٌ جديد يجعل سعر القطعتين
-- القديم ليس عرضاً يُرفض (`INVALID_PAIR_PRICE`) لا يُقبل بصمت.
--
-- `order_items.pair_price` لقطة وقت الطلب كـ`price`: تعديل العرض أو إزالته
-- لاحقاً لا يمسّ طلباً قائماً، و`line_total` المحفوظ هو ما دفعه الزبون. الطلبات
-- القائمة كلها NULL — لم يكن لها عرض، ولا يُختلق لها.

ALTER TABLE products
  ADD COLUMN pair_price NUMERIC(12, 2);

ALTER TABLE products
  ADD CONSTRAINT products_pair_price_offer
    CHECK (pair_price IS NULL OR (price IS NOT NULL AND pair_price >= price AND pair_price < 2 * price));

ALTER TABLE order_items
  ADD COLUMN pair_price NUMERIC(12, 2);
