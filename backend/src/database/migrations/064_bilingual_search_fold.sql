-- 064_bilingual_search_fold.sql
-- البحث بالكردية: مطابقة `name_ckb`، وطيّ صور الحروف المتكافئة.
--
-- ═══ العطل (2026-09-27) ═══
-- البحث يطابق `products.name` (العربي) ومرادفات الأنمي وحدها. الأسماء
-- الكردية تعيش في `name_ckb` (الهجرة 046، ومملوءة منذ 047) ولم يكن أي مسار
-- بحث يقرؤها — فـ«تیشێرت» لا يجد «تیشێرتی جوجوتسو کایسن» مهما كُتب. وحتى
-- حين تكون الكلمة في النصّ، الكردية تُكتب بصورٍ مختلفة للحرف نفسه بحسب
-- لوحة المفاتيح: `ی`/`ي`/`ى`، `ک`/`ك`، `ە`/`ه`/هاءٌ يتبعها فاصلٌ صفري (ZWNJ)،
-- `ھ`، ومحارف غير مرئية (ZWNJ، التطويل). ILIKE يقارن نقاط الترميز حرفياً،
-- فيفشل البحث بصمت بين صورتين صحيحتين.
--
-- ═══ الإصلاح ═══
-- `search_fold` يحوّل أي نصّ إلى «مفتاح بحث»: يُطبَّق على النصّ المخزَّن
-- وعلى ما يكتبه الزبون بالدالة نفسها، فتلتقي الصور المتكافئة. لا قائمة
-- كلمات ولا نقحرة — البيانات المخزَّنة نفسها تصير قابلة للبحث.
--   1. NFKC: صور العرض (U+FB50–U+FEFF) وتفكيك الهمزة إلى صورتها المركّبة.
--   2. حذف ما لا يغيّر الكلمة: التشكيل، الألف الخنجرية، علامات المصحف،
--      التطويل، العلامات المركّبة المتبقية بعد NFKC (صورٌ قديمة كـ`ی`+U+0306)،
--      ومحارف العرض غير المرئية (ZWNJ/ZWJ/LRM/RLM/ALM).
--   3. طيّ الحروف (مقصودٌ أنه متسامح — كما يتسامح بحث اللاتينية مع حالة
--      الحرف): الياءات → `ی`، الكافان → `ک`، الهاءات والتاء المربوطة → `ه`،
--      الألفات المهموزة → `ا`، `ؤ`/`ۆ` → `و`، `ێ` → `ی`، `ڵ` → `ل`،
--      `ڕ` → `ر` (صاحب لوحة عربية لا يستطيع كتابة حروف الكردية الخاصة)،
--      والأرقام الشرقية → غربية.
--   4. `lower` للحروف اللاتينية (`A3`، `One Piece`).
-- الدالة IMMUTABLE فتُفهرَس: فهرس trigram على المفتاح المطويّ يحلّ محلّ
-- فهرس الاسم الخام في مسار البحث العام.

CREATE OR REPLACE FUNCTION search_fold(value TEXT)
RETURNS TEXT
LANGUAGE sql
IMMUTABLE
STRICT
PARALLEL SAFE
AS $$
  SELECT lower(
    translate(
      regexp_replace(
        normalize(value, NFKC),
        '[\u0300-\u036F\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED\u0640\u200B-\u200F\u061C\u2066-\u2069\uFEFF]',
        '',
        'g'
      ),
      'يىېێكەھةۀۂہأإآٱؤۆڵڕ٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹',
      'ییییکههههههااااوولر01234567890123456789'
    )
  );
$$;

COMMENT ON FUNCTION search_fold(TEXT) IS
  'مفتاح بحث متسامح للعربية والكردية: NFKC، حذف التشكيل والمحارف غير المرئية، طيّ صور الحروف المتكافئة، أرقام غربية، lower.';

-- نمط LIKE «يحتوي» من نصّ الزبون: مطويٌّ بالدالة نفسها ثم مُهرَّب، فلا
-- يصير `%` أو `_` (ولا `％` الذي يطويه NFKC إلى `%`) نمطاً.
CREATE OR REPLACE FUNCTION search_like_pattern(query TEXT)
RETURNS TEXT
LANGUAGE sql
IMMUTABLE
STRICT
PARALLEL SAFE
AS $$
  SELECT '%' || replace(replace(replace(search_fold(query), '\', '\\'), '%', '\%'), '_', '\_') || '%';
$$;

-- مستند البحث للمنتج: الاسمان معاً. الفاصل سطرٌ جديد لا يكتبه أحد في مربّع
-- البحث، فلا تمتدّ مطابقةٌ من آخر العربي إلى أول الكردي.
CREATE OR REPLACE FUNCTION product_search_text(name TEXT, name_ckb TEXT)
RETURNS TEXT
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
AS $$
  SELECT search_fold(COALESCE(name, '') || E'\n' || COALESCE(name_ckb, ''));
$$;

CREATE INDEX IF NOT EXISTS idx_products_search_trgm
  ON products USING GIN (product_search_text(name, name_ckb) gin_trgm_ops);
