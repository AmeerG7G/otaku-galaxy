-- 045_delivery_discount_excess.sql
-- الفائض من خصم التوصيل — الجزء الذي تجاوز رسوم التوصيل.
--
-- خصم التوصيل مسقوف برسوم التوصيل منذ هجرة ٠١٩: `min(الخام، الرسوم)`. وما
-- زاد على الرسوم كان يُلقى في `Math.min` ولا يُسجَّل في أي مكان. مثال المتجر:
-- رسوم ٥٬٠٠٠ ومنتج خصمه ١٬٠٠٠ للقطعة وست قطع ⇒ الخام ٦٬٠٠٠، يأخذ الزبون
-- ٥٬٠٠٠ ويصير توصيله صفراً، ويختفي الألف الباقي بلا أثر.
--
-- هذا العمود يسجّله. وهو **ليس** خصماً للزبون بأي معنى: لا يُنقص مجموع
-- المنتجات ولا `discount` ولا `total`، ولا يظهر في أي استجابة يقرأها العميل.
-- مبلغٌ محتفَظ به للمتجر، مربوطٌ بطلبه، للتدقيق.
--
-- يتبع نمط اللقطة المالية القائم على `orders` نفسه (`products_total`,
-- `delivery_fee`, `discount`, `loyalty_discount`, `delivery_discount`):
-- NUMERIC(12,2) بقيود تحرس ثوابته. ولا جدول أستاذ جديد — لا يوجد في المشروع
-- نموذج محاسبي للمتجر، واختراعُ واحدٍ لأجل رقمٍ واحد قرارٌ ليس هذا موضعه.
ALTER TABLE orders
  ADD COLUMN delivery_discount_excess NUMERIC(12,2) NOT NULL DEFAULT 0
    CHECK (delivery_discount_excess >= 0);

-- [CRITICAL] لا فائض إلا وقد استُهلكت الرسوم كلها.
--
-- الفائض معناه الوحيد «الخام تجاوز الرسوم»، وذلك يقتضي أن الخصم بلغ الرسوم
-- تماماً. فائضٌ موجب مع خصمٍ دون الرسوم يعني حساباً خاطئاً: مبلغٌ قُيِّد
-- للمتجر بينما الزبون ما يزال يدفع توصيلاً كان من حقه أن يُخصم. القاعدة
-- تمنع هذا الصفّ من الوجود أصلاً، فلا يعتمد الثابت على صحّة شيفرةٍ وحدها.
ALTER TABLE orders
  ADD CONSTRAINT orders_delivery_excess_only_when_fee_covered
    CHECK (
      delivery_discount_excess = 0
      OR delivery_discount = delivery_fee
    );
