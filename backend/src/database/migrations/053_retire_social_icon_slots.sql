-- 053_retire_social_icon_slots.sql
-- أيقونات التواصل أصولٌ ثابتة، ووصفُ الفتحات المشتركة يسمّي شاشاتها.
--
-- ═══ ١) إسقاط فتحات أيقونات التواصل ═══
-- قرار منتج (2026-09-15): أيقونات تيك توك وإنستغرام وواتساب ليست شخصياتٍ
-- تُبدَّل من اللوحة؛ تبقى أصولاً ثابتة في التطبيق، والرابط وحده يُدار من
-- إعدادات المتجر (`store_settings.social_*` — جدولٌ آخر لا يُمسّ). الفتحات
-- الثلاث (الهجرة ٠٣٢) تُسقَط كما أُسقطت فتحات الشاشات المحذوفة (٠٣١، ٠٤٩):
-- صورُها تسقط معها (ON DELETE CASCADE)، وسجلّات `media_files` والملفات على
-- القرص تبقى — حذفها قرار تنظيف منفصل. التطبيق لم يعد يعرف هذه المفاتيح
-- (`VisualSlots`)، فبقاؤها كان يَعِد بتغييرٍ لا يقع.
DELETE FROM visual_slots
 WHERE slot_key IN ('social_tiktok', 'social_instagram', 'social_whatsapp');

-- ═══ ٢) وصفٌ يسمّي كل شاشةٍ تظهر فيها الفتحة ═══
-- المسؤول يقرأ «شاشة إنشاء الحساب — ترويسة» ولا يعرف أن الشخصية نفسها تظهر
-- في شاشة «بانتظار الموافقة». الفتحات المشتركة أو المشروطة تُوصف بمواضعها
-- كلّها كما يستهلكها الكود فعلاً (تدقيق 2026-09-15). النصّ المزروع وحده
-- يُصحَّح — وصفٌ عدّله المسؤول بيده لا يُمسّ (كما في ٠٤٩).
UPDATE visual_slots
   SET location = 'تُستخدم في: شاشة إنشاء الحساب (الترويسة) · شاشة «بانتظار الموافقة» بعد طلب التسجيل'
 WHERE slot_key = 'register_character'
   AND location = 'شاشة إنشاء الحساب — ترويسة';

UPDATE visual_slots
   SET location = 'تُستخدم في: شاشة استعادة كلمة المرور (الترويسة) · شاشة «بانتظار الموافقة» بعد طلب الاستعادة'
 WHERE slot_key = 'forgot_password_character'
   AND location = 'شاشة استعادة كلمة المرور — ترويسة';

UPDATE visual_slots
   SET location = 'تُستخدم في: شاشة تسجيل الدخول · شاشة إنشاء الحساب · شاشة استعادة كلمة المرور — اللوحة السفلية في الثلاث'
 WHERE slot_key = 'auth_cta_character'
   AND location = 'اللوحة السفلية في شاشات المصادقة الثلاث';

UPDATE visual_slots
   SET location = 'تُستخدم في: تبويب السلة · تبويب المفضلة — دعوة تسجيل الدخول للزائر'
 WHERE slot_key = 'guest_prompt_character'
   AND location = 'دعوة الدخول في السلة والمفضلة';

-- اللوحة الرئيسية وبطاقات الترويج تعرض صورة البنر إن ضبط المسؤول واحدة؛
-- الشخصية تظهر فقط حين لا صورة للبنر. وصفٌ لا يقول ذلك يجعل المسؤول يبدّل
-- شخصيةً ثم لا يراها على الشاشة.
UPDATE visual_slots
   SET location = 'الرئيسية — اللوحة العلوية الكبيرة (تظهر فقط حين لا صورة للبنر الرئيسي)'
 WHERE slot_key = 'home_hero_character'
   AND location = 'الرئيسية — اللوحة العلوية الكبيرة';

UPDATE visual_slots
   SET location = 'الرئيسية — البطاقة الترويجية الأولى في الشريط الأفقي (تظهر فقط حين لا صورة لبنرها)'
 WHERE slot_key = 'home_promo_primary_character'
   AND location = 'الرئيسية — بطاقة «موسم المدرسة»';

UPDATE visual_slots
   SET location = 'الرئيسية — البطاقات الترويجية من الثانية فصاعداً في الشريط الأفقي (تظهر فقط حين لا صورة لبنرها)'
 WHERE slot_key = 'home_promo_secondary_character'
   AND location = 'الرئيسية — بطاقة «خصومات فعّالة»';
