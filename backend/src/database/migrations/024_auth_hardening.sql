-- 024_auth_hardening.sql
-- تقوية المصادقة: حالة تحقّق صريحة، إبطال الجلسات، وتتبّع إرسال الرموز.
--
-- ثلاث ثغرات يعالجها هذا الملف:
--
-- 1) لم يكن للتحقق أثرٌ في القاعدة إطلاقاً. الحساب يُنشأ عند التسجيل ويُسجَّل
--    دخوله فوراً، فرمز التحقق كان زينةً لا بوابة. `phone_verified_at` يجعل
--    «محقَّق» حالةً حقيقية يفحصها تسجيل الدخول.
--
-- 2) التوكن كان بلا إبطال: إيقاف الحساب لا يمنع التوكن المُصدَر قبله من
--    العمل حتى انتهاء صلاحيته (٧ أيام). `token_version` يسمح بإبطال كل
--    التوكنات السابقة لمستخدم واحد بزيادة رقم واحد.
--
-- 3) إعادة إرسال الرمز لم تكن محدودة، فالرقم الواحد يُقصف برسائل بلا سقف.
--    `verification_codes.created_at` موجود أصلاً؛ نضيف فهرساً يخدم عدّ
--    الإرسالات الأخيرة بسرعة.

-- ===== 1) حالة التحقق =====
ALTER TABLE users ADD COLUMN IF NOT EXISTS phone_verified_at TIMESTAMPTZ;

-- المستخدمون الحاليون سجّلوا قبل وجود هذه البوابة، وبعضهم أتمّ التحقق فعلاً
-- بينما لم يُحفظ الأثر. إسقاط الجميع خارج التطبيق عقوبةٌ على خطأ الخادم لا
-- خطئهم، فنعتبرهم محقَّقين بأثر رجعي (طابع الإنشاء) ونطبّق البوابة على من
-- يسجّل بعد الآن. هذا هو المقصود بـ«عدم كسر الجلسات القائمة بلا ضرورة».
UPDATE users SET phone_verified_at = created_at WHERE phone_verified_at IS NULL;

-- ===== 2) إبطال التوكنات =====
-- كل توكن يحمل نسخته؛ عدم التطابق مع الصف = توكن مُبطَل. الافتراضي 0 يطابق
-- التوكنات القديمة التي لا تحمل الحقل أصلاً، فلا تنقطع جلسة قائمة بلا سبب.
ALTER TABLE users ADD COLUMN IF NOT EXISTS token_version INTEGER NOT NULL DEFAULT 0;

-- ===== 3) تسريع عدّ الإرسالات الأخيرة لرقم واحد =====
CREATE INDEX IF NOT EXISTS idx_verification_codes_phone_created
  ON verification_codes (phone, created_at DESC);
