-- 067_bilingual_banner_content.sql
-- نصّ البنر بلغتين منفصلتين: عنوانٌ وسطرٌ ثانٍ بالعربية، وعنوانٌ وسطرٌ ثانٍ بالكردية.
--
-- ═══════════════ القرار (2026-09-29) ═══════════════
--
-- المسؤول يكتب نصّ البنر بكل لغةٍ بيده، في حقولٍ مستقلة — كمحتوى المنتج
-- (066). لا ترجمة آلية، ولا حقلٌ يُنسخ من الآخر، والبنر يبقى صفاً واحداً:
-- الصورة والموضع والوجهة والترتيب لا تتكرّر بتكرّر اللغة.
--
-- ═══════════════ الأعمدة ═══════════════
--
-- نفس اصطلاح 046/066 لا أعمدة `title_ar` جديدة: `title`/`subtitle` هما
-- **العربية** (قائمان منذ 004/030)، و`title_ckb` قائمٌ منذ 046. الناقص هو
-- السطر الثاني بالكردية وحده — لم يكن له عمود، فكان كل بنرٍ بسطرٍ ثانٍ يظهر
-- للزبون الكردي بسطرٍ عربي. نسخُ العربية إلى أعمدةٍ جديدة كان سيخلق مصدرين
-- للنصّ نفسه يتباعدان عند أول تعديل.
--
-- ═══════════════ الاختياري يبقى اختيارياً ═══════════════
--
-- نصّ البنر لم يكن إلزامياً قطّ: بنرٌ بصورةٍ وحدها مشروع. فلا يُفرض هنا
-- (ولا في الـAPI) نصٌّ بأي لغة. وحين تنقص لغةٌ تُعرض الأخرى (الكردية ← العربية،
-- والعربية ← الكردية) — اختيارٌ وقت القراءة، لا نصٌّ يُكتب في العمود الناقص.
--
-- ═══════════════ البنرات القائمة ═══════════════
--
-- لا عمود عربي يُمسّ. لا يُختلق نصٌّ كردي: ما لم يكتبه المسؤول (أو هجرة 047)
-- يبقى `NULL` — وهو الصورة **الوحيدة** لـ«ناقص» في العمودين الكرديين، فالفراغ
-- والمسافات في `title_ckb` تُحوَّل إلى `NULL` هنا ويمنعها قيدٌ بعدها. القيدان
-- يصدقان على كل صفٍّ قائم بعد التحويل، فلا يفشل تعديلٌ لاحق (إعادة ترتيب،
-- إيقاف) على بنرٍ قديم.

-- ═══════════════ ١ · السطر الثاني بالكردية ═══════════════

ALTER TABLE banners
  ADD COLUMN IF NOT EXISTS subtitle_ckb TEXT;

-- ═══════════════ ٢ · «ناقص» صورةٌ واحدة: NULL ═══════════════

UPDATE banners
   SET title_ckb = NULL
 WHERE title_ckb IS NOT NULL AND btrim(title_ckb) = '';

ALTER TABLE banners
  DROP CONSTRAINT IF EXISTS banners_title_ckb_not_blank;
ALTER TABLE banners
  ADD CONSTRAINT banners_title_ckb_not_blank
    CHECK (title_ckb IS NULL OR btrim(title_ckb) <> '');

ALTER TABLE banners
  DROP CONSTRAINT IF EXISTS banners_subtitle_ckb_not_blank;
ALTER TABLE banners
  ADD CONSTRAINT banners_subtitle_ckb_not_blank
    CHECK (subtitle_ckb IS NULL OR btrim(subtitle_ckb) <> '');

-- ═══════════════ ٣ · معنى الأعمدة ═══════════════

COMMENT ON COLUMN banners.title IS
  'عنوان البنر بالعربية كما كتبه المسؤول. اختياري: NULL = بلا عنوان عربي (تُعرض الكردية إن وُجدت).';
COMMENT ON COLUMN banners.subtitle IS
  'السطر الثاني بالعربية. اختياري: '''' = بلا سطر عربي (يُعرض الكردي إن وُجد).';
COMMENT ON COLUMN banners.title_ckb IS
  'عنوان البنر بالكردية (سوراني) كما كتبه المسؤول. NULL = ناقص (يُعرض العربي)، لا فراغ أبداً.';
COMMENT ON COLUMN banners.subtitle_ckb IS
  'السطر الثاني بالكردية (سوراني) كما كتبه المسؤول. NULL = ناقص (يُعرض العربي)، لا فراغ أبداً.';
